-- 1. Расширение для работы исключающего ограничения по времени (защита от гонок)
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- 2. Точки доступа (Корпуса, общежития)
CREATE TABLE access_points (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               external_id BIGINT NOT NULL UNIQUE,
                               name VARCHAR(255) NOT NULL,
                               short_name VARCHAR(255),
                               archival BOOLEAN NOT NULL DEFAULT FALSE,
                               tags VARCHAR(500)
);

-- 3. Комнаты
CREATE TABLE rooms (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       number VARCHAR(255),
                       name VARCHAR(255),
                       floor INT NOT NULL,
                       type VARCHAR(255) NOT NULL DEFAULT 'RESIDENTIAL' CHECK (type IN ('RESIDENTIAL', 'COMMON')),
                       access_point_id BIGINT NOT NULL REFERENCES access_points(id) ON DELETE CASCADE
);
-- 4. Пользователи (Студенты, админы)
CREATE TABLE users (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       username VARCHAR(255) NOT NULL UNIQUE,
                       role VARCHAR(255) DEFAULT 'USER',
                       name VARCHAR(255),
                       surname VARCHAR(255),
                       patronymic VARCHAR(255),
                       description VARCHAR(255),
                       groups VARCHAR(255),
                       last_synced_at TIMESTAMP,
                       room_id BIGINT REFERENCES rooms(id) ON DELETE SET NULL
);

-- 5. Связь пользователей и разрешенных точек доступа (Many-to-Many)
CREATE TABLE user_access_points (
                                    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                                    access_point_id BIGINT NOT NULL REFERENCES access_points(id) ON DELETE CASCADE,
                                    PRIMARY KEY (user_id, access_point_id)
);

-- 6. Ресурсы (Стиральные машины, коворкинги и т.д.)
CREATE TABLE resources (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           name VARCHAR(255) NOT NULL,
                           is_available BOOLEAN NOT NULL DEFAULT TRUE,
                           is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
                           active_from TIME NOT NULL,
                           active_to TIME NOT NULL,
                           access_type VARCHAR(255) NOT NULL CHECK (access_type IN ('CAMPUS_DORM_COMMON', 'FACULTY_RESTRICTED')),
                           description TEXT,
                           rules TEXT,
                           access_point_id BIGINT NOT NULL REFERENCES access_points(id) ON DELETE CASCADE,
                           room_id BIGINT NOT NULL REFERENCES rooms(id) ON DELETE CASCADE
);

-- 7. Ограничения доступа по факультетам для ресурсов
CREATE TABLE resource_allowed_faculties (
                                            resource_id BIGINT NOT NULL REFERENCES resources(id) ON DELETE CASCADE,
                                            faculty_id BIGINT
);

-- 8. Записи бронирования
CREATE TABLE records (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         record_date TIMESTAMP NOT NULL,
                         booking_date DATE NOT NULL,
                         start_time TIME NOT NULL,
                         end_time TIME NOT NULL,
                         status VARCHAR(255) NOT NULL CHECK (status IN ('CONFIRMED', 'CANCELED', 'COMPLETED', 'REJECTED', 'NOSHOW')),
                         user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                         resource_id BIGINT NOT NULL REFERENCES resources(id) ON DELETE CASCADE
);

-- 9. ЗАЩИТА ОТ ДВОЙНЫХ БРОНИРОВАНИЙ (Контроль гонок на уровне СУБД)
ALTER TABLE records
    ADD CONSTRAINT no_overlap
    EXCLUDE USING gist (
    resource_id WITH =,
    tsrange(
        (booking_date + start_time),
        (booking_date + end_time)
    ) WITH &&
)
WHERE (status = 'CONFIRMED');